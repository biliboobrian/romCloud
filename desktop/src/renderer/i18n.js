  const UNITS = { en: ['B', 'KB', 'MB', 'GB', 'TB'], fr: ['o', 'Ko', 'Mo', 'Go', 'To'] };
  let lang = 'en';

  function t(key, vars = {}) {
    const text = dict[lang][key] ?? dict.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] !== undefined ? String(vars[name]) : m));
  }

  /** Message d'une erreur renvoyée par le processus principal. */
  function errorText(error) {
    if (!error) return '';
    if (error.key && (dict[lang][error.key] || dict.en[error.key])) return t(error.key, error.vars);
    return error.message || String(error);
  }

  function formatSize(bytes) {
    const units = UNITS[lang] || UNITS.en;
    if (!bytes) return `0 ${units[0]}`;
    const i = Math.min(units.length - 1, Math.floor(Math.log(bytes) / Math.log(1024)));
    const value = new Intl.NumberFormat(lang, { maximumFractionDigits: i ? 1 : 0, minimumFractionDigits: i ? 1 : 0 })
      .format(bytes / 1024 ** i);
    return `${value} ${units[i]}`;
  }

  window.I18N = {
    t,
    errorText,
    formatSize,
    setLanguage(code) {
      lang = dict[code] ? code : 'en';
      document.documentElement.lang = lang;
    },
    get language() {
      return lang;
    },
    keys: (code) => Object.keys(dict[code] || {}),
  };
